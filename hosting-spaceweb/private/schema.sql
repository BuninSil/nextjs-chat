CREATE TABLE IF NOT EXISTS reports (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  ticket VARCHAR(24) NOT NULL,
  install_hash CHAR(64) NOT NULL,
  ip_hash CHAR(64) NOT NULL,
  app_version VARCHAR(32) NOT NULL,
  version_code INT UNSIGNED NOT NULL DEFAULT 0,
  category VARCHAR(16) NOT NULL DEFAULT 'other',
  manufacturer VARCHAR(80) NOT NULL DEFAULT '',
  device_model VARCHAR(100) NOT NULL DEFAULT '',
  android_version VARCHAR(30) NOT NULL DEFAULT '',
  sdk SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  vpn_state VARCHAR(16) NOT NULL DEFAULT 'unknown',
  network_type VARCHAR(32) NOT NULL DEFAULT 'unknown',
  description VARCHAR(500) NOT NULL DEFAULT '',
  diagnostics TEXT NOT NULL,
  status ENUM('new','in_progress','resolved','duplicate') NOT NULL DEFAULT 'new',
  admin_note VARCHAR(2000) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_ticket (ticket),
  KEY idx_status_created (status, created_at),
  KEY idx_install_created (install_hash, created_at),
  KEY idx_ip_created (ip_hash, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
